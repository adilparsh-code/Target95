/**
 * Get learning outcomes for a specific chapter
 */
export const getLearningOutcomes = (classId, chapterId) => {
  const classOutcomes = learningOutcomes[classId];
  if (!classOutcomes) return [];
  
  for (const unitId in classOutcomes) {
    const unitOutcomes = classOutcomes[unitId];
    if (unitOutcomes[chapterId]) {
      return unitOutcomes[chapterId];
    }
  }
  
  return [];
};

export default learningOutcomes;