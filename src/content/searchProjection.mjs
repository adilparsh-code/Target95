// Answer-free search projection of the unified catalog.
//
// Global search is mounted in the Navbar on every page, including during a mock test, so it
// must never carry answer keys. The catalog itself contains correct answers, model answers and
// explanations, so search reads this projection instead: only the columns below, nothing else.
// Pure module (no app imports) so the generator, the client and `node --test` share it.

/** The ONLY question fields search may carry. Adding a column here is a security decision. */
export const SEARCH_QUESTION_COLUMNS = Object.freeze([
  "id",
  "question",
  "chapterId",
  "chapterSlug",
  "subject",
  "tags",
  "board",
  "difficulty",
  "type",
]);

export const SEARCH_CHAPTER_COLUMNS = Object.freeze(["id", "slug", "title"]);

/**
 * @param {import('./schema.mjs').UnifiedQuestion[]} questions live (non-quarantined) questions
 * @param {{id: string, slug: string, title: string}[]} chapters
 */
export function buildSearchIndex(questions, chapters) {
  return {
    questionColumns: [...SEARCH_QUESTION_COLUMNS],
    chapterColumns: [...SEARCH_CHAPTER_COLUMNS],
    chapters: chapters.map((chapter) => SEARCH_CHAPTER_COLUMNS.map((column) => String(chapter[column] ?? ""))),
    questions: questions.map((question) =>
      SEARCH_QUESTION_COLUMNS.map((column) => (column === "tags" ? [...(question.tags || [])].map(String) : String(question[column] ?? "")))),
  };
}

export function renderSearchIndexModule(index) {
  return [
    "// GENERATED by scripts/generate-search-index.mjs - do not edit by hand.",
    "// Answer-free projection for global search. Run `npm run generate:search-index` after changing question data.",
    `export const SEARCH_INDEX = ${JSON.stringify(index)};`,
    "",
  ].join("\n");
}

const rowToQuestion = (index, row) => Object.fromEntries(index.questionColumns.map((column, i) => [column, row[i]]));

/**
 * Same matching rule the search box always used: the term must appear in the question text,
 * chapter title, chapter slug, subject or a tag (case-insensitive).
 * @returns {{id, question, chapterId, chapterSlug, subject, tags, board, difficulty, type, chapterTitle, chapterSlugResolved}[]}
 */
export function searchQuestionIndex(index, term) {
  const needle = String(term || "").toLowerCase();
  if (!needle) return [];
  const chapterById = new Map(index.chapters.map(([id, slug, title]) => [id, { slug, title }]));
  const results = [];
  for (const row of index.questions) {
    const question = rowToQuestion(index, row);
    const chapter = chapterById.get(question.chapterId) || null;
    const haystack = [question.question, chapter?.title, question.chapterSlug, question.subject, ...question.tags].join(" ").toLowerCase();
    if (!haystack.includes(needle)) continue;
    results.push({ ...question, chapterTitle: chapter?.title || "", chapterSlugResolved: chapter?.slug || "" });
  }
  return results;
}
